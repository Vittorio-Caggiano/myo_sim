"""Writes warp_impl/poly_kernels.py: one explicit kernel per polynomial (dim, order).

The arithmetic order matches myo_warp.poly_eval term by term, so results stay bit-identical; only the table lookups
and the per-thread power table go away. Run: python -m myo_sim.warp.gen_poly_kernels
"""

from __future__ import annotations

from pathlib import Path

COMBOS = [(1, 2), (1, 3), (2, 4), (2, 5), (2, 6), (2, 8), (3, 2), (3, 3), (3, 4), (3, 9), (4, 3), (4, 4), (6, 4)]
HEAD = '''"""Generated by gen_poly_kernels.py. Do not edit."""
import warp as wp

wp.set_module_options({"enable_backward": False})

'''
SIG = """@wp.kernel
def path_d{d}_o{o}(
    group: wp.array(dtype=int), coef: wp.array(dtype=float), coef_adr: wp.array(dtype=int),
    qposadr: wp.array2d(dtype=int), dofadr: wp.array2d(dtype=int), qpos: wp.array2d(dtype=float),
    qvel: wp.array2d(dtype=float), state: wp.array3d(dtype=float), grad: wp.array3d(dtype=float),
):
    worldid, k = wp.tid()
    i = group[k]
    a = coef_adr[i]
"""


def exponents(dim: int, order: int) -> list[tuple[int, ...]]:
    def rec(d, o):
        if d == 0:
            yield ()
            return
        for i in range(o + 1):
            for tail in rec(d - 1, o - i):
                yield (i,) + tail

    return list(rec(dim, order))


def kernel(d: int, o: int) -> str:
    out = [SIG.format(d=d, o=o)]
    for j in range(d):
        out.append(f"    q{j} = qpos[worldid, qposadr[i, {j}]]\n")
        for e in range(1, o + 1):
            prev = "1.0" if e == 1 else f"p{j}_{e - 1}"
            out.append(f"    p{j}_{e} = {prev} * q{j}\n")
    out.append("    L = float(0.0)\n")
    for j in range(d):
        out.append(f"    g{j} = float(0.0)\n")
    for k, ex in enumerate(exponents(d, o)):
        out.append(f"    c = coef[a + {k}]\n    t = c\n")
        for j in range(d):
            if ex[j]:
                out.append(f"    t = t * p{j}_{ex[j]}\n")
        out.append("    L = L + t\n")
        for j in range(d):
            if not ex[j]:
                continue
            out.append(f"    t = c * {float(ex[j])}\n")
            for i in range(d):
                ei = ex[i]
                if i == j:
                    if ei - 1 > 0:
                        out.append(f"    t = t * p{i}_{ei - 1}\n")
                elif ei:
                    out.append(f"    t = t * p{i}_{ei}\n")
            out.append(f"    g{j} = g{j} + t\n")
    out.append("    V = float(0.0)\n")
    for j in range(d):
        out.append(f"    V = V + g{j} * qvel[worldid, dofadr[i, {j}]]\n    grad[worldid, i, {j}] = g{j}\n")
    out.append("    state[worldid, i, 3] = L\n    state[worldid, i, 4] = V\n\n\n")
    return "".join(out)


def main() -> None:
    body = HEAD + "".join(kernel(d, o) for d, o in COMBOS)
    body += "KERNELS = {\n" + "".join(f"    ({d}, {o}): path_d{d}_o{o},\n" for d, o in COMBOS) + "}\n"
    Path(__file__).with_name("poly_kernels.py").write_text(body)


if __name__ == "__main__":
    main()
