"""Companion (non-XML) data for ``myofullbody_simple`` Bolt-parity physics.

Generated by ``python -m myo_sim.build.fullbody_simple_bolt_assets``. Feeds
``myo_sim.warp.MuscleSystem`` (DGF, ``path="tendon"``) and
``myo_sim.warp.ContactSystem`` (Hunt–Crossley), and the MuJoCo C plugin via
``write_plugin_spec`` / ``myo_sim.physics.make_musculoskeletal(backend=\"c\", ...)``.

Formulation and sprinter-style contact / F0 overrides follow Bolt and msk_envs (Apache-2.0); see NOTICE.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

_DIR = Path(__file__).resolve().parent / "models" / "fullbody_simple"


def load_muscles() -> list:
    return list(np.load(_DIR / "muscles.npy", allow_pickle=True))


def load_contact() -> dict:
    cz = np.load(_DIR / "contact.npz")
    return {"geom_flat": cz["geom_flat"], "pairs": cz["pairs"], "naconmax": int(cz["naconmax"])}


def load_map() -> dict:
    return json.loads((_DIR / "map.json").read_text())


def load_limits() -> list[dict]:
    """Joint-limit force records for MuscleSystem / write_spec."""
    from myo_sim.physics import limits_from_map

    return limits_from_map(load_map())


def write_plugin_spec(path, *, limits=None, contact=True, met_flags=15, aerobic=1.0, effort=1.0) -> str:
    """Write a ``myo.muscles`` spec from packaged fullbody_simple assets (same records as Warp)."""
    from myo_sim.plugin import cmyo

    if limits is None:
        limits = load_limits()
    if contact is True:
        contact = load_contact()
    elif contact is False:
        contact = None
    path = str(path)
    cmyo.write_spec(
        path,
        load_muscles(),
        met_flags=met_flags,
        aerobic=aerobic,
        effort=effort,
        limits=limits,
        contact=contact,
    )
    return path
